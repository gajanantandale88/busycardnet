        about = "International air cargo consolidation and rapid domestic courier sorting center.",
        normX = -0.90f,
        normY = 0.88f
      )
    )

    // Recalculate dynamic coordinates and distance from the caller's actual GPS location
    return rawPlaces.map { place ->
      // If user's GPS is different from default Mumbai center, dynamically project places relative to user location
      val (dynamicLat, dynamicLng) = if (Math.abs(currentLat - DEFAULT_CENTER_LAT) > 0.001 || Math.abs(currentLng - DEFAULT_CENTER_LNG) > 0.001) {
        val dLat = place.latitude - DEFAULT_CENTER_LAT
        val dLng = place.longitude - DEFAULT_CENTER_LNG
        Pair(currentLat + dLat, currentLng + dLng)
      } else {
        Pair(place.latitude, place.longitude)
      }

      val distResults = FloatArray(1)
      Location.distanceBetween(
        currentLat,
        currentLng,
        dynamicLat,
        dynamicLng,
        distResults
      )
      val calculatedDistance = distResults[0].toInt().coerceAtLeast(40)
      place.copy(
        latitude = dynamicLat,
        longitude = dynamicLng,
        distanceMeters = calculatedDistance
      )
    }
  }

  /**
   * Filter places strictly within a given radius in meters (default 500m)
   */
  fun filterPlacesWithinRadius(
    places: List<LocalMapPlaceItem>,
    radiusMeters: Int = 500,
    placeType: PlaceType? = null,
    categoryCode: String? = null,
    searchQuery: String? = null,
    onlyOpenNow: Boolean = false
  ): List<LocalMapPlaceItem> {
    val smartIntent = if (!searchQuery.isNullOrBlank()) SmartSearchIntentEngine.analyzeQuery(searchQuery) else null

    return places.filter { place ->
      val matchesRadius = place.distanceMeters <= radiusMeters
      val matchesType = placeType == null || place.placeType == placeType
      val matchesCategory = categoryCode.isNullOrBlank() || categoryCode == "ALL" || place.professionCode.equals(categoryCode, ignoreCase = true)
      val matchesOpen = !onlyOpenNow || place.isOpenNow
      val matchesSmartIntent = smartIntent != null && place.professionCode.equals(smartIntent.requiredProfessionCode, ignoreCase = true)
      val matchesSearch = searchQuery.isNullOrBlank() ||
        matchesSmartIntent ||
        place.name.contains(searchQuery, ignoreCase = true) ||
        place.categoryTitle.contains(searchQuery, ignoreCase = true) ||
        place.ownerOrContact.contains(searchQuery, ignoreCase = true) ||
        place.servicesOrProducts.any { it.contains(searchQuery, ignoreCase = true) } ||
        place.address.contains(searchQuery, ignoreCase = true)

      matchesRadius && matchesType && matchesCategory && matchesOpen && matchesSearch
    }.sortedBy { it.distanceMeters }
  }
